export type Lang = 'en' | 'ur' | 'ar'
export type Direction = 'ltr' | 'rtl'
export type Theme = 'light' | 'dark' | 'system'

export function getDir(lang: Lang): Direction {
  return lang === 'en' ? 'ltr' : 'rtl'
}

export function getUIFont(lang: Lang): string {
  if (lang === 'ur') return "'Noto Nastaliq Urdu', serif"
  if (lang === 'ar') return "'Amiri', serif"
  return "'Inter', sans-serif"
}

export function phraseLabel(lang: Lang, n: number, total: number): string {
  if (lang === 'ur') return `${total} میں سے ${n} جملہ`
  if (lang === 'ar') return `العبارة ${n} من ${total}`
  return `Phrase ${n} of ${total}`
}

